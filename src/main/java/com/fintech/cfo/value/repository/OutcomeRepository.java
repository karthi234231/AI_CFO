package com.fintech.cfo.value.repository;

/**
 * Read and write access to the {@code outcomes} table.
 *
 * <p>Key design decision: this repository is scoped to what has been
 * <em>observed</em>. It knows nothing about whether an observation may be counted,
 * because that is {@link RealizedValueRepository}'s question and answering both in
 * one place would re-create the merge this schema deliberately avoids.
 *
 * <p>Expected query semantics:
 * <ul>
 * <li>{@code findById(org, id)} - tenant-scoped; the primary key alone is not
 * authorization.</li>
 * <li>{@code findByOpportunity(org, oppId)} ordered by {@code measured_at DESC} -
 * serves {@code ix_outcomes_opp (opportunity_id, measured_at DESC)}. Descending
 * because the dominant read is "what happened most recently", so the index
 * ordering matches the access path rather than being sorted at run time.</li>
 * <li>{@code findByOrganizationAndMeasuredBetween(org, from, to)} - serves
 * {@code ix_outcomes_org_date (organization_id, measured_at DESC)} and backs
 * period reports. Bounds are half-open on {@code measured_at} and expressed as
 * business dates, so a report for a period is a predicate on stored columns rather
 * than a timestamp comparison that would exclude same-day rows depending on the
 * time of day they were written.</li>
 * <li>{@code findByExecution(org, executionId)} - the measurements taken about one
 * attempt. Serves the reconciliation between an execution and the outcomes that
 * settled it, and must return them in {@code measured_at} order because that is
 * the sequence the recovery happened in.</li>
 * <li>{@code findByOpportunityAndMeasuredAtBetween(org, oppId, from, to)} - the
 * bound check that an outcome's amount does not exceed the claim it settles. Scoped
 * to the window so the ceiling is applied against what was measured in the relevant
 * period, not against a lifetime total that would let a later oversized outcome pass
 * an earlier one.</li>
 * <li>A status-filtered variant for the counting gate: only {@code CONFIRMED}
 * outcomes may back a realized value, so a query that returns {@code PENDING} or
 * {@code DISPUTED} rows here is answering a reporting question, not a realization
 * one, and the two must not share a method.</li>
 * </ul>
 *
 * <p>Aggregation belongs to the service, not to a database {@code SUM}. A sum
 * computed in SQL cannot enforce a currency check, cannot exclude
 * {@code REVERSED} correctly without a status predicate that is easy to forget, and
 * cannot raise the business-rule exception this module uses to signal that
 * attributions do not reconcile. Money is summed in Java where the invariant can
 * accompany the arithmetic.
 *
 * <p>No method here accepts a caller-supplied {@code organizationId} as an
 * authority - it is always the tenant of the authenticated principal.
 */
