package com.fintech.cfo.value.controller;

/**
 * HTTP entry point for recording and reading outcomes - the module's measured
 * claims about what actually happened.
 *
 * <p>Key design decision: this boundary ends at measurement. There is deliberately
 * no endpoint here that counts an amount as recovered. Realization is a separate
 * accounting decision with its own invariants - currency agreement, the terminal
 * states, reversal-as-a-new-row - and exposing it on the same controller as the
 * measurement form would invite a single "record what happened" call that
 * simultaneously books a portfolio number, letting one request bypass the review
 * that separates "the effect happened" from "we may count it".
 *
 * <p>Expected surface, one-to-one with {@code RecordOutcomeRequest} and
 * {@code OutcomeResponse}:
 * <ul>
 * <li>{@code POST /api/outcomes} - record a measurement against an opportunity,
 * optionally naming the execution it settles.</li>
 * <li>{@code GET /api/outcomes/{id}} - a single outcome, tenant-scoped.</li>
 * <li>{@code GET /api/outcomes?opportunityId=} - measurement history for one
 * claim, most recent first, served by {@code ix_outcomes_opp}.</li>
 * <li>{@code GET /api/outcomes?from=&amp;to=} - period reporting, served by
 * {@code ix_outcomes_org_date}. Both bounds are business dates applied
 * half-open against the stored {@code measured_at} DATE, so a period report is a
 * column predicate rather than a timestamp comparison that would move rows between
 * periods depending on the time of day they were written.</li>
 * <li>{@code POST /api/outcomes/{id}/reverse} - record that a confirmed outcome
 * turned out to be wrong, as a status change on the same row. Never an edit of
 * {@code measuredAmount}: the amount first booked and the amount it later
 * disappeared by both have to stay readable.</li>
 * </ul>
 *
 * <p>Never accepts an {@code organizationId}. Tenancy comes from the authenticated
 * principal in the service layer, and an outcome outside the caller's tenant is
 * reported as not-found rather than forbidden.
 *
 * <p>The two bounds are enforced here rather than merely passed through: a measured
 * amount may not exceed the claim it settles, and a non-zero amount requires
 * provenance - a measurement method, or a recorded execution. Both surface as the
 * typed exceptions the shared {@code GlobalExceptionHandler} renders. Clamping is
 * specifically not offered, because a clamped outcome reports a recovery nobody
 * made, silently, in the one field the product exists to get right.
 *
 * <p>All responses are {@code ApiResponse<T>} of a DTO; entities are never
 * returned. A write that records a measurement is an auditable business event and
 * the service writes it to {@code AuditService}.
 */
