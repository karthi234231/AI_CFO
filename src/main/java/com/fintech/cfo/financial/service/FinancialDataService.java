/**
 * Module-level entry point for financial master data and transactions: the
 * service other modules call, and the place where period and reconciliation
 * invariants are enforced across entity types.
 *
 * <p>Key design decision: this service is the only place allowed to move a
 * transaction into an accounting period, and the period gate is a precondition
 * of the write rather than a check performed afterwards. The decision it makes
 * has two distinct halves that are deliberately not merged: whether the posting
 * date falls inside the period window
 * ({@code AccountingPeriod.contains}), and whether the period still accepts a
 * posting at all ({@code AccountingPeriodStatus.acceptsPostingOn}). A date can
 * sit inside a locked period and still have to be refused, because the closed
 * report containing it is already signed.
 *
 * <p>Responsibilities expected here:
 * <ul>
 * <li>Own the tenant and the transaction boundary for every cross-entity write:
 * customer, then invoice and lines, then the transactions that settle it.</li>
 * <li>Delegate parsing and identity to {@code FinancialDataNormalizer} and the
 * per-entity normalizers, so this service makes no formatting or matching
 * decisions of its own.</li>
 * <li>Reject a posting into a period that is not open, and report the period
 * status rather than absorbing the transaction into the nearest open one -
 * silently re-perioding a transaction would make a signed report disagree with
 * the ledger.</li>
 * <li>Keep cash-flow reporting free of snapshot rows by using
 * {@code TransactionType.affectsCashFlow()} rather than summing every transaction
 * in the period, which would double-count the opening and closing balances the
 * period is defined by.</li>
 * <li>Expose reconciliation of an invoice's reported totals against its lines,
 * returning the recomputed figures alongside the reported ones so a reviewer sees
 * the variance rather than only a verdict.</li>
 * <li>Report the lineage - source system, record, file and row - of anything it
 * returns, so a reported amount is traceable to the uploaded file.</li>
 * </ul>
 *
 * <p>Expected to hold no state between calls: a batch that partially fails must
 * not influence the identity or period decision of the next one.
 */
